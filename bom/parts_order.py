"""Everything but the Thonk parts for Spore (Marblesy), Orchid (Plaitsy), Moss
(Side FXy) and Mycelium (the stereo mixer), as one list: the four modules'
BOM files summed part by part, with a column per module. Shop parts first,
by kind and value; then what is made or built elsewhere (the PCBs, the
Seed breakouts, the display).

Reads <module>/hardware/bom/<module>-bom.csv (run each module's
hardware/tools/bom.py first). Writes bom/parts-order.md and
bom/parts-order.csv. The Thonk parts are in bom/thonk-order.md.
Run from the repo root:  python bom/parts_order.py
"""
import collections
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = [("Spore", "marbles"), ("Orchid", "plaits"), ("Moss", "side-fx"), ("Mycelium", "stereo-mixer")]
GROUPS = ["Panel parts", "Modules", "Chips", "Semiconductors", "Resistors", "Capacitors", "Connectors",
          "Mechanical", "PCBs"]
ELSEWHERE = {"JLCPCB", "OSHWLab / JLCPCB", "Eckstein", "Waveshare"}     # not ordered from a parts shop


def size(part):
    """The value in a resistor or capacitor line, for sorting (ohms or farads); 0 for anything else."""
    m = re.match(r"Resistor ([\d.]+) ?([kM]?)", part)
    if m:
        return float(m.group(1)) * {"": 1, "k": 1e3, "M": 1e6}[m.group(2)]
    m = re.match(r"Capacitor ([\d.]+) ?(pF|nF|µF)", part)
    if m:
        return float(m.group(1)) * {"pF": 1e-12, "nF": 1e-9, "µF": 1e-6}[m.group(2)]
    return 0.0


def main():
    rows = collections.OrderedDict()          # part -> {"group", "source", "per": {panel name: qty}, "notes": []}
    for name, folder in MODULES:
        with open(os.path.join(ROOT, folder, "hardware", "bom", f"{folder}-bom.csv"), encoding="utf-8") as f:
            for r in csv.DictReader(f):
                if r["Source"] == "Thonk":
                    continue
                row = rows.setdefault(r["Part"], {"group": r["Group"], "source": r["Source"],
                                                  "per": collections.Counter(), "notes": []})
                row["per"][name] += int(r["Qty"])
                note = re.sub(r"from [\w-]+-routed\.epro2|the panel board in [\w-]+-routed\.epro2; ?", "", r["Note"]).strip("; ")
                if note and note not in row["notes"]:
                    row["notes"].append(note)
    names = [n for n, _ in MODULES]
    shop = sorted(((p, r) for p, r in rows.items() if r["source"] not in ELSEWHERE),
                  key=lambda kv: (GROUPS.index(kv[1]["group"]), size(kv[0]), kv[0]))
    other = sorted(((p, r) for p, r in rows.items() if r["source"] in ELSEWHERE),
                   key=lambda kv: (kv[1]["source"], kv[0]))
    with open(os.path.join(ROOT, "bom", "parts-order.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Qty", "Group", "Part"] + names + ["Suggested source", "Note"])
        for part, row in shop + other:
            w.writerow([sum(row["per"].values()), row["group"], part] + [row["per"][n] or "" for n in names]
                       + [row["source"], "; ".join(row["notes"])])

    def table(sel, with_group):
        head = "| Qty | " + ("Kind | " if with_group else "Source | ") + "Part | " + " | ".join(names) + " | Note |"
        out = [head, "|---|---|---|" + "---|" * len(names) + "---|"]
        for part, row in sel:
            first = row["group"] if with_group else row["source"]
            out.append(f"| {sum(row['per'].values())} | {first} | {part} | "
                       + " | ".join(str(row["per"][n] or "") for n in names) + f" | {'; '.join(row['notes'])} |")
        return out

    md = ["# Parts order: Spore, Orchid, Moss, Mycelium (without Thonk)", "",
          "Generated by `bom/parts_order.py` from the four modules' BOMs (`<module>/docs/bom.md`); don't edit",
          "it by hand. One of each module. The Thonk parts are in [thonk-order.md](thonk-order.md); refs and",
          "per-board detail are in each module's BOM: [Spore](../marbles/docs/bom.md),",
          "[Orchid](../plaits/docs/bom.md), [Moss](../side-fx/docs/bom.md), [Mycelium](../stereo-mixer/docs/bom.md).",
          "", "## Shop parts", ""]
    md += table(shop, True)
    md += ["", f"{len(shop)} lines, {sum(sum(r['per'].values()) for _, r in shop)} parts.", "",
           "## Made or built elsewhere", ""]
    md += table(other, False) + [""]
    with open(os.path.join(ROOT, "bom", "parts-order.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(f"{len(shop)} shop lines ({sum(sum(r['per'].values()) for _, r in shop)} parts), {len(other)} made elsewhere")


if __name__ == "__main__":
    main()
