"""One Thonk order for Spore (Marblesy), Orchid (Plaitsy), Moss (Side FXy) and
Mycelium (the stereo mixer): the four modules' Thonk BOM files summed part by
part, with a column per module. Header strips are summed as pins, since they
are cut to length anyway.

Reads <module>/hardware/bom/<module>-bom-thonk.csv (run each module's
hardware/tools/bom.py first). Writes bom/thonk-order.md and bom/thonk-order.csv.
Run from the repo root:  python bom/thonk_order.py
"""
import collections
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = [("Spore", "marbles"), ("Orchid", "plaits"), ("Moss", "side-fx"), ("Mycelium", "stereo-mixer")]
GROUPS = ["Panel parts", "Modules", "Chips", "Semiconductors", "Resistors", "Capacitors", "Connectors",
          "Mechanical", "PCBs"]


def main():
    rows = collections.OrderedDict()          # part -> {"group", "per": {panel name: qty}, "notes": set}
    for name, folder in MODULES:
        with open(os.path.join(ROOT, folder, "hardware", "bom", f"{folder}-bom-thonk.csv"), encoding="utf-8") as f:
            for r in csv.DictReader(f):
                part, qty = r["Part"], int(r["Qty"])
                m = re.match(r"(Male pin header, 2\.54 mm|Female header, 2\.54 mm, 8\.5 mm tall): (.*)", part)
                if m:                          # 2 × 1×8, 3 × 1×4 -> pins
                    qty = sum(int(n) * int(p) for n, p in re.findall(r"(\d+) × 1×(\d+)", m.group(2)))
                    part = m.group(1) + ", pins (cut to length)"
                row = rows.setdefault(part, {"group": r["Group"], "per": collections.Counter(), "notes": []})
                row["per"][name] += qty
                note = "" if part.startswith("Knob") else r["Note"]     # the module columns say which knobs
                if note and not m and note not in row["notes"]:
                    row["notes"].append(note)
    for part, row in rows.items():
        if part.endswith("pins (cut to length)"):
            row["notes"] = [f"Thonk's Male + Female Header Bag, or {-(-sum(row['per'].values()) // 40)} × 40-pin strips "
                            "or more (cutting wastes a few)"]
    order = sorted(rows.items(), key=lambda kv: (GROUPS.index(kv[1]["group"]), kv[0]))
    names = [n for n, _ in MODULES]
    with open(os.path.join(ROOT, "bom", "thonk-order.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Qty", "Part"] + names + ["Note"])
        for part, row in order:
            w.writerow([sum(row["per"].values()), part] + [row["per"][n] or "" for n in names] + ["; ".join(row["notes"])])
    md = ["# Thonk order: Spore, Orchid, Moss, Mycelium", "",
          "Generated by `bom/thonk_order.py` from the four modules' Thonk BOMs (`<module>/docs/bom.md`); don't",
          "edit it by hand. One of each module. Header strips are counted in pins.", "",
          "| Qty | Part | " + " | ".join(names) + " | Note |", "|---|---|" + "---|" * len(names) + "---|"]
    for part, row in order:
        md.append(f"| {sum(row['per'].values())} | {part} | " + " | ".join(str(row["per"][n] or "") for n in names)
                  + f" | {'; '.join(row['notes'])} |")
    md += ["", "Everything else (Tayda, Mouser, JLCPCB, the breakouts) is in each module's `docs/bom.md`:",
           "[Spore](../marbles/docs/bom.md), [Orchid](../plaits/docs/bom.md), [Moss](../side-fx/docs/bom.md),",
           "[Mycelium](../stereo-mixer/docs/bom.md).", ""]
    with open(os.path.join(ROOT, "bom", "thonk-order.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(f"{len(order)} Thonk lines, {sum(sum(r['per'].values()) for _, r in order)} items")


if __name__ == "__main__":
    main()
