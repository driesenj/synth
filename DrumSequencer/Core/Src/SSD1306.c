void SSD1306_DrawChar(int16_t x, int16_t y, char ch, uint8_t colour)
{
    if (ch < 0x20 || ch > 0x7E) ch = '?';
    const uint8_t *glyph = _font5x7[ch - 0x20];

    for (uint8_t col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (uint8_t row = 0; row < 7; row++) {
            if (line & (1 << row))
                SSD1306_DrawPixel(x + col, y + row, colour);
            else
                SSD1306_DrawPixel(x + col, y + row, !colour);
        }
    }
}

void SSD1306_DrawString(int16_t x, int16_t y, const char *str, uint8_t colour)
{
    int16_t cx = x, cy = y;
    while (*str) {
        if (cx + 6 > SSD1306_WIDTH) { // wrap
            cx = 0;
            cy += 9; // 7px glyph + 2px gap
        }
        if (cy + 7 > SSD1306_HEIGHT) break; // off-screen, stop
        SSD1306_DrawChar(cx, cy, *str++, colour);
        cx += 6; // 5px glyph + 1px gap
    }
}

uint8_t SSD1306_UpdateStart(void)
{
    if (_dma_busy || _page_next < SSD1306_PAGES) return 0;   /* still sending */

    /* Reset the GDDRAM window. Blocking, 6 × 2 bytes ≈ 150 µs. Horizontal
       addressing mode was set in Init, so the pointer auto-increments and
       wraps across all eight strips without further commands. */
    _cmd(0x21); _cmd(0); _cmd(SSD1306_WIDTH - 1);
    _cmd(0x22); _cmd(0); _cmd(SSD1306_PAGES - 1);

    _page_next = 0;
    SSD1306_Service();
    return 1;
}

void SSD1306_Service(void)
{
    if (_dma_busy) return;
    if (_page_next >= SSD1306_PAGES) return;

    uint8_t p = _page_next;
    _dma_busy = 1;

    if (HAL_I2C_Master_Transmit_DMA(_hi2c, SSD1306_I2C_ADDR << 1,
                                    _page[p], 1 + SSD1306_WIDTH) != HAL_OK) {
        _dma_busy = 0;          /* bus busy or error — retry next iteration */
        return;
    }
    _page_next = (uint8_t)(p + 1);
}

uint8_t SSD1306_BusBusy(void)    { return _dma_busy; }
uint8_t SSD1306_UpdateBusy(void) { return _dma_busy || (_page_next < SSD1306_PAGES); }

void SSD1306_TxCpltISR(void) { _dma_busy = 0; }

void SSD1306_ErrorISR(void)
{
    _dma_busy  = 0;
    _page_next = SSD1306_PAGES;    /* abandon the frame; next redraw retries */
}
